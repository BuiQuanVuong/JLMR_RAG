"""Build a retrieval evaluation set with known answers.

Two kinds of test questions, generated by Claude Haiku 5.5 from papers sampled across all eras:
  passage - a specific question answered by one passage in the middle of a paper (gold = that paper
            and passage). Tests `ask`.
  topic   - a short "find papers about ..." query written from a paper's abstract (gold = that paper).
            Tests `search`.

Output: eval/questions.jsonl (one JSON object per line). Review and edit it by hand if you like:
delete bad questions, reword them. eval.py only reads this file.

Usage:  python make_eval.py [--passage 60] [--topic 20] [--seed 7]
"""
import argparse
import json
import random
import re
import sys

import anthropic

from common import ROOT, connect, utf8_console

OUT = ROOT / "eval" / "questions.jsonl"
MODEL = "claude-haiku-5-5"
ERAS = [(1, 12), (13, 20), (21, 26)]   # volumes 2000-2011, 2012-2019, 2020-2025

SCHEMA = {
    "type": "object",
    "properties": {
        "usable": {"type": "boolean"},
        "question": {"type": "string"},
    },
    "required": ["usable", "question"],
    "additionalProperties": False,
}

PASSAGE_PROMPT = """Below is a passage from a machine learning research paper. Write ONE question that a \
researcher might type into a literature search tool, and that this passage answers specifically.

Rules:
- Do not mention the paper, its title, its authors, or say "this paper" / "the authors".
- Paraphrase: do not copy distinctive phrases or sentences from the passage. Standard technical terms \
(method names, concepts) are fine.
- Make it specific enough that this passage is a strong answer, not something any ML paper would answer.
- 10 to 30 words, a single question.
- If the passage is not suitable (mostly garbled math, a table of numbers, acknowledgements, references, \
boilerplate, or too fragmentary to ask about), set usable to false and question to "".

Paper title (for context only, do not use its wording): {title}

Passage:
{text}"""

HARD_PROMPT = """Below is a passage from a machine learning research paper. Write ONE question, answered \
specifically by this passage, as it would be asked by a researcher who understands the problem but does NOT \
know this paper's terminology.

Rules:
- Describe the idea in plain, general words. Do NOT use the passage's method or algorithm names, acronyms, \
dataset names, notation, or any distinctive multi-word technical phrase from it. Use synonyms or describe \
the concept instead (for example "a way to pick how wide the similarity function should be" rather than \
"bandwidth selection for the Gaussian kernel").
- Do not mention the paper, its title or its authors.
- Still specific enough that this passage is a strong answer.
- 12 to 35 words, a single question.
- If the passage is not suitable (mostly garbled math, a table of numbers, acknowledgements, references, \
boilerplate, or too fragmentary to ask about), set usable to false and question to "".

Paper title (for context only, do not use its wording): {title}

Passage:
{text}"""

TOPIC_PROMPT ="""Below is the abstract of a machine learning research paper. Write a short search query \
(4 to 10 words) that a researcher looking for papers on this paper's main topic would type.

Rules:
- Describe the topic or problem, not the paper. Do not copy the title; avoid its exact phrasing.
- No author names, no quotes, no question mark.
- If the abstract is missing or unusable, set usable to false and question to "".

Title (for context only): {title}

Abstract:
{abstract}"""


def generate(client, prompt):
    msg = client.messages.create(
        model=MODEL, max_tokens=2000, output_config={"effort": "low", "format": {"type": "json_schema",
                                                                              "schema": SCHEMA}},
        messages=[{"role": "user", "content": prompt}])
    if msg.stop_reason != "end_turn":
        return None
    data = json.loads(next(b.text for b in msg.content if b.type == "text"))
    return data["question"].strip() if data["usable"] and data["question"].strip() else None


def body_chunks(con, key):
    """Readable, non-bibliography passages from the middle 15%-70% of a paper."""
    rows = con.execute("SELECT id, seq, page_start, page_end, text FROM chunks "
                       "WHERE paper_key=? AND is_ref=0 ORDER BY seq", (key,)).fetchall()
    n = len(rows)
    out = []
    for r in rows[int(n * 0.15): int(n * 0.7)]:
        letters = len(re.findall(r"[A-Za-z]", r["text"]))
        if letters / max(len(r["text"]), 1) > 0.7:
            out.append(r)
    return out


def main():
    utf8_console()
    ap = argparse.ArgumentParser()
    ap.add_argument("--passage", type=int, default=60)
    ap.add_argument("--topic", type=int, default=20)
    ap.add_argument("--seed", type=int, default=7)
    ap.add_argument("--hard", type=int, default=0,
                    help="append N hard (vocabulary-mismatch) passage questions to the existing set")
    a = ap.parse_args()
    existing = []
    if OUT.exists():
        if not a.hard:
            sys.exit(f"{OUT} already exists - delete it first, or use --hard N to append hard questions.")
        existing = [json.loads(l) for l in open(OUT, encoding="utf-8") if l.strip()]
    elif a.hard:
        sys.exit("Build the standard set first (run without --hard).")

    rng = random.Random(a.seed)
    con = connect()
    client = anthropic.Anthropic()
    papers = {era: [r for r in con.execute(
        "SELECT key, title, abstract, n_chunks FROM papers WHERE status='done' AND volume BETWEEN ? AND ?",
        era).fetchall()] for era in ERAS}
    for era in papers.values():
        rng.shuffle(era)

    questions, used = [], {q["gold_paper"] for q in existing}

    def take(kind, want):
        made, era_i, tries = 0, 0, 0
        while made < want and tries < want * 4:
            tries += 1
            era = ERAS[era_i % len(ERAS)]
            era_i += 1
            p = next((p for p in papers[era] if p["key"] not in used), None)
            if p is None:
                continue
            used.add(p["key"])
            if kind in ("passage", "hard"):
                cands = body_chunks(con, p["key"]) if (p["n_chunks"] or 0) >= 10 else []
                if not cands:
                    continue
                c = rng.choice(cands)
                prompt = HARD_PROMPT if kind == "hard" else PASSAGE_PROMPT
                q = generate(client, prompt.format(title=p["title"], text=c["text"]))
                item = dict(gold_chunk=c["id"], gold_seq=c["seq"], pages=[c["page_start"], c["page_end"]],
                            difficulty=kind if kind == "hard" else "standard")
            else:
                if not p["abstract"] or len(p["abstract"]) < 200:
                    continue
                q = generate(client, TOPIC_PROMPT.format(title=p["title"], abstract=p["abstract"]))
                item = {}
            if not q:
                continue
            made += 1
            qtype = "passage" if kind == "hard" else kind
            questions.append(dict(id=f"{kind[0]}{made:03d}", type=qtype, question=q, gold_paper=p["key"],
                                  gold_title=p["title"], **item))
            print(f"[{kind} {made}/{want}] {q}", flush=True)

    try:
        if a.hard:
            rng.seed(a.seed + 1000)
            take("hard", a.hard)
        else:
            take("passage", a.passage)
            take("topic", a.topic)
    except anthropic.AuthenticationError:
        sys.exit("Anthropic API key rejected - check .env")
    OUT.parent.mkdir(exist_ok=True)
    with open(OUT, "a" if a.hard else "w", encoding="utf-8") as f:
        for q in questions:
            f.write(json.dumps(q, ensure_ascii=False) + "\n")
    print(f"\nWrote {len(questions)} questions to {OUT} ({len(existing) + len(questions)} in total)")


if __name__ == "__main__":
    main()
